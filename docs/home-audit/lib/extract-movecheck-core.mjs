/**
 * 跳过「结构上不算数」的区间：字符串/模板串、`//` 行注释、`/* *\/` 块注释。
 *
 * 若 `src[k]` 落在这样一个区间里，返回**该区间之后**的下标；否则返回 `-1`。
 * 三处扫描（单行判据、找函数体、配平花括号）共用这一个 —— 见文件头「统一的跳过原语」。
 *
 * ⚠️ `//` 注释**停在那个换行符上**（返回换行符的下标，不是它之后）：
 *    换行本身还要被调用方处理（它可能正是「语句末」）。
 *
 * ⚠️ **没闭合的串/块注释返回 `src.length + 1`**（不是 `src.length`）——
 *    用来把它与「正好在文本末尾闭合」区分开。这两个下标的区别是必须的：
 *    `const EMPTY_FILTER_VALUE = '__EMPTY__'` 的收尾引号**恰好**是最后一个字符
 *    ⇒ 闭合时 `skipInert` 返回 `length`；若用 `>= length` 判「没闭合」，
 *    这条完全正常的单行声明就会被硬闸误判（实测踩到）。`length + 1` 是哨兵值，
 *    合法下标永远取不到它。
 */
function skipInert(src, k) {
  const c = src[k]
  if (c === '"' || c === "'" || c === '`') {
    for (let j = k + 1; j < src.length; j++) {
      if (src[j] === '\\') { j++; continue }
      if (src[j] === c) return j + 1
    }
    return src.length + 1 // 没闭合：吃到文件尾
  }
  if (c === '/' && src[k + 1] === '/') {
    const nl = src.indexOf('\n', k)
    return nl < 0 ? src.length : nl // 行注释本来就可以没有换行收尾 —— 不算「没闭合」
  }
  if (c === '/' && src[k + 1] === '*') {
    const e = src.indexOf('*/', k + 2)
    return e < 0 ? src.length + 1 : e + 2
  }
  return -1
}

/** `src[k]` 是不是注释（而不是字符串）的开头 —— `skipInert` 的返回值要按这个分岔。 */
const isCommentAt = (src, k) => src[k] === '/' && (src[k + 1] === '/' || src[k + 1] === '*')

/**
 * 行尾续行记号：一行的**最后一个代码字符**是这些之一 ⇒ 这条语句没写完。
 *
 * 每一条都对应仓库里真实存在的形状（见文件头「路 3」）：
 * `=`（`type TextFilterKey =` / `const engine: OrderLines =`）·
 * `=>`（`const sqCell = (l: Line) =>`，**曾造成 4 个名字假绿**）·
 * `|` `&`（联合/交叉类型断行）· `&&` `||` `??`（逻辑运算断行）·
 * `+`（字符串拼接断行）· `,`（参数表）· `.`（成员链）· `?` `:`（三元断行）·
 * `(` `[` `{`（括号没闭合 —— 其实括号栈会先拦下，这里是冗余的保险）·
 * `<`（**泛型形参/实参断行**：`export interface DocSheetRenderApi<` +
 * `  C = DocSheetConfig,` 这种写法，2026-09-20 Task 3.7 补）。
 *
 * ⚠️ 一份完整、合法的声明**不可能**以这些字符收尾 ⇒ 这条判据不会把完整声明带出去。
 *    唯一的例外是「行尾注释恰好以这些字符收尾」（`const x = 1 // 比例 =`），
 *    所以调用方必须传**去掉注释后**的文本（实现里用 `lastCode` 保证）。
 *
 * ⚠️ `'<'` 那条**不能省**（Task 3.7 实测）：`<` `>` 不在括号栈里（`stack` 只装 `(` `[` `{`），
 *    所以泛型断行的首行**收支正好为 0**；若行尾表里又没有 `<`，它就命中下面的「路 1 快车道」
 *    ⇒ 只切 1 行、配平、不报错、拿去比对。实测受害 6 处**顶层**声明（`docSheetUi.ts` 的
 *    `DocSheetRenderApi`/`DocSheetUiApi`/`DocSheetDialogProfile`/`DocSheetUiProfile`、
 *    `productionSheetUiProfile.ts::ProductionSheetUiProfile`、
 *    `qualifiedLabelUiProfile.ts::QualifiedLabelUiProfile`），真声明分别 **22/10/24/45/5/5** 行。
 *    合法声明不可能以 `<` 收尾，`const a < b` 也不是完整语句 ⇒ 这条不会误伤完整声明。
 */
const TAIL_CONTINUES = ['=', '=>', '|', '&', '&&', '||', '??', '+', ',', '.', '?', ':', '(', '[', '{', '<']

/**
 * 行首续行记号：**下一行的第一个非空字符**是这些之一 ⇒ 上一行只是断行，语句没写完。
 *
 * 专治 prettier 风格（记号写在下一行行首），行尾表看不见这种：
 *
 * ```ts
 * type TextFilterKey =
 *   | 'client_name'      ← 行尾是 'client_name'，只有看**下一行行首**才知道还要继续
 *   | 'order_date'
 * ```
 *
 * 这几个记号**都不可能是顶层声明的开头** ⇒ 不会把切片带进下一个声明里。
 */
const HEAD_CONTINUES = ['|', '&', '.', '?', ':']

const tailContinues = (text) => {
  const t = text.replace(/\s+$/, '')
  return TAIL_CONTINUES.some((tok) => t.endsWith(tok))
}

/** 从换行符 `from` 之后开始看：跳过空行与 `//` 注释行，判下一行代码的首字符。 */
function headContinues(src, from) {
  let k = from
  while (k < src.length) {
    const nl = src.indexOf('\n', k + 1)
    const t = src.slice(k + 1, nl < 0 ? src.length : nl).trim()
    if (t === '' || t.startsWith('//') || t.startsWith('/*') || t.startsWith('*')) {
      if (nl < 0) return false
      k = nl
      continue
    }
    return HEAD_CONTINUES.some((tok) => t.startsWith(tok))
  }
  return false
}

/**
 * 括号收支（**跳过字符串与注释**）。`depth` 是最终收支、`min` 是过程最深（负=中途多出右括号）、
 * `open` 表示最后一段是**没闭合的字符串/块注释**（切到头了）。
 *
 * ⚠️ `//` 注释停在换行上、`nl < 0` 时返回 `src.length` —— 那**不算** `open`：
 *    行注释本来就可以没有换行结尾（切片末尾那一行就是这样）。只有字符串与块注释才算。
 */
export function bracketBalance(text) {
  let depth = 0
  let min = 0
  let open = false
  for (let k = 0; k < text.length; k++) {
    const s = skipInert(text, k)
    if (s >= 0) {
      // `length + 1` 是 skipInert 的「没闭合」哨兵 —— 见它上面的注释。
      if (s > text.length) open = true
      k = s - 1
      continue
    }
    const c = text[k]
    if (c === '(' || c === '[' || c === '{') depth++
    else if (c === ')' || c === ']' || c === '}') { depth--; if (depth < min) min = depth }
  }
  return { depth, min, open }
}

/**
 * 比对的**核心**：返回首个不同行的行号（1 基），两串一致则返回 0。
 *
 * ⚠️ 主比对循环与 `--selftest` **共用这一个函数**（不是各写一份）——
 * 否则自测验的就不是主循环真正跑的那段代码，等于没测。
 */
export function firstDiffLine(a, b) {
  const A = a.split('\n')
  const B = b.split('\n')
  for (let i = 0; i < Math.max(A.length, B.length); i++) {
    if (A[i] !== B[i]) return i + 1
  }
  return 0
}

/**
 * 归一化：逐行去行首缩进、去行尾空白、丢空行。
 *
 * ⚠️ **不 strip `export`** —— 新文件里每个搬出去的东西都多一个 `export`，
 * 而那正是靠 `rewrites` 逐条声明的（见各守卫的 `rewrites`）。
 * 顺手 strip 掉的话，「多加了 `export` 却没登记」就再也看不见了。
 *
 * ⚠️ `//` 注释**保留**：注释也是文档，改了要看得见。
 */
export const norm = (s) =>
  s
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l !== '')
    .join('\n')

/** 切出声明整段的**内部**实现。返回 `{ text, fast }`；`fast` = 走的是「单行声明」快车道。 */
function rawSlice(src, name) {
  // 允许行首缩进 —— 新文件里它们缩在工厂函数内部（多 2 格）。
  // ⚠️ 用 `[ \t]*` 而不是 `\s*`：`\s` 会把**前一个换行**也吃进去，`m.index` 就落在空行上，
  //    后面按行切全错（表现为「HEAD 里找不到」）。
  const re = new RegExp(
    `^[ \\t]*(?:export\\s+)?(?:async\\s+)?(?:function|const|let|var|type|interface)\\s+${name}\\b`,
    'm',
  )
  const m = re.exec(src)
  if (!m) return null
  const i = m.index
  const firstNl = src.indexOf('\n', i)
  const firstLine = src.slice(i, firstNl < 0 ? src.length : firstNl)
  const firstBal = bracketBalance(firstLine)

  // ── 路 1：单行声明 ──────────────────────────────────────────────────────
  // 收支 ≤ 0（见文件头：负收支=正则字面量里的右括号，那一行本来就是完整的）·
  // 行尾不是续行记号 · 首行没有没闭合的字符串 ·
  // **下一行行首也不是续行记号**（2026-09-20 Task 3.7 补的第四个条件 —— 见下）。
  //
  // ⚠️⚠️ **这条快车道必须看下一行**，否则它会**静默切短**：判据三条全中 ⇒ 直接返回首行，
  //    `sliceFn` 在 `fast: true` 时还会**跳过结构性硬闸**（见 `sliceFn`：`if (r.text != null && !r.fast)`）
  //    ⇒ 切出来 1 行、括号配平、**不报错、拿去比对**。实测（Task 3.7，`decl-sweep.mjs`）
  //    这一类共 **33 处**（含 **6 处顶层**），形状是「首行括号正好配平、声明却在下一行继续」：
  //    ```ts
  //    const theadCells = cols          // 收支 0、行尾是 `cols`（不在行尾表里）
  //      .map(…)                        // ← 下一行行首是 `.` —— 没有这个条件就切不到它
  //    ```
  //    「首行括号正好配平、声明却在下一行继续」这一族**此前只在路 3 的 lookahead 里被管**，
  //    路 1 一次都没调用过 `headContinues` ⇒ 两张记号表都在、这条路上却形同虚设。
  //    文档（`docs/2026-09-20-home-hui-split.md` §9f）当时已宣称「已修」—— 是**文档与代码不一致**。
  if (
    firstBal.depth <= 0 &&
    !firstBal.open &&
    !tailContinues(firstLine) &&
    // `firstNl < 0`（首行一直延伸到文件尾）时传 `src.length - 1` —— 那里没有「下一行」，
    // `headContinues` 会返回 false。别另算一个 `firstNl`，它上面几行已经算好了。
    !headContinues(src, firstNl < 0 ? src.length - 1 : firstNl)
  ) {
    return { text: firstLine.replace(/\s+$/, ''), fast: true }
  }

  /*
   * ── 路 2/3：跨行扫描 ────────────────────────────────────────────────────
   * 三种结局：找到函数体（`body`）· 找到语句末（`stmtEnd`）· 兜底（`bail`）。
   *
   * `stack` 记未闭合的 `(` `[` `{`。它同时干三件事：决定「换行能不能跨过去」、
   * 「这个 `{` 够不够格当函数体」、以及「配平到哪儿」。
   * `lastCode` 记**最后一个代码字符**的下标（字符串的收尾引号算代码，注释不算）——
   * 判「行尾续行记号」只能看它，看整行末尾会被行尾注释骗到。
   */
  const stack = []
  let body = -1
  let stmtEnd = -1
  let bail = false
  let lastCode = -1
  /*
   * 「栈空时**见过一个闭合的 `)`**」的闩 —— 函数体 `{` 的**顺序**要求，见文件头「路 2」第 4 条。
   * 只在 `)` 把栈**弹空**的那一刻置位，此后**不再复位**（函数体的 `{` 一定在参数表之后；
   * 而参数表之后可能还夹着返回类型、`=>`、`[`…，复位会让这些形状又找不到体）。
   */
  let sawParen = false
  for (let k = i; k < src.length; k++) {
    const s = skipInert(src, k)
    if (s >= 0) {
      // 字符串的收尾引号是代码（`const x = 'a='` 的末尾是引号，不是 `=`）；
      // 注释整个不算代码 —— `lastCode` 不动。
      if (!isCommentAt(src, k)) lastCode = s - 1
      k = s - 1
      continue
    }
    const c = src[k]
    if (c === '\n') {
      // 只在**栈空**时收工；栈非空说明还在参数表/表达式里面，继续走。
      // 栈空也要再判两条：本行末尾是不是续行记号、下一行行首是不是续行记号。
      if (stack.length === 0 && !tailContinues(src.slice(i, lastCode + 1)) && !headContinues(src, k)) {
        stmtEnd = k
        break
      }
      continue
    }
    if (c !== ' ' && c !== '\t' && c !== '\r') lastCode = k
    if (c === '{' && stack.length === 0 && sawParen) {
      const rest = src.slice(k + 1)
      if (/^\s*\n/.test(rest)) { body = k; break }
      // 否则是「一行内写完」的类型字面量/对象字面量（`): { label: string }[] {`），
      // 跳过它的配对。这里也要跳过字符串与注释，否则一个 `'}'` 字面量就能骗走配对。
      let d = 0
      for (let j = k; j < src.length; j++) {
        const s2 = skipInert(src, j)
        if (s2 >= 0) { j = s2 - 1; continue }
        if (src[j] === '{') d++
        else if (src[j] === '}') { d--; if (d === 0) { k = j; lastCode = j; break } }
      }
      continue
    }
    if (c === '(' || c === '[' || c === '{') stack.push(c)
    else if (c === ')' || c === ']' || c === '}') {
      // 多出来的右括号（正则字面量等）—— 栈已经不可信了，整段退回按行切。
      if (stack.length === 0) { bail = true; break }
      stack.pop()
      // 这个 `)` 把栈**弹空了** ⇒ 参数表（或调用实参表）已经闭合 —— 见文件头「路 2」第 4 条。
      if (c === ')' && stack.length === 0) sawParen = true
    }
  }

  if (body < 0) {
    // ── 路 4：兜底 ────────────────────────────────────────────────────────
    if (bail) return { text: firstLine.replace(/\s+$/, ''), fast: false }
    if (stmtEnd >= 0) return { text: src.slice(i, stmtEnd).replace(/\s+$/, ''), fast: false }
    // ⚠️ 走到**文件尾**、且括号已配平 ⇒ 这条语句就在文件尾收口，只是后面没有换行可停 ——
    //    切到文件尾。（Task 3.5 实测踩到：`fixtures/hui-pre-3b.ts` 的最后一个声明
    //    `diaoColumns` 就是这么收尾的，其组件侧同名声明在文件中间、后面有换行
    //    ⇒ 两边一个切 1 行、一个切 3 行，报出一处**假**差异。不补这条就是自己制造噪声。）
    if (stack.length === 0) return { text: src.slice(i).replace(/\s+$/, ''), fast: false }
    // 括号没配平（正则字面量、被注释吃掉的括号…）⇒ 退回旧口径「只切第一行」。宁可少验，不可错验。
    return { text: firstLine.replace(/\s+$/, ''), fast: false }
  }

  // ── 找到函数体 `{` 了：花括号配对，切到配对的 `}` ─────────────────────────
  // ⚠️ **必须跳过字符串与注释**（2026-09-20 补）：函数体里的注释/字符串中出现不平衡的
  //    `{` `}` 会把配对骗走 ⇒ 切出一段错误文本。旧版这里只看引号、不看注释。
  let d = 0
  for (let k = body; k < src.length; k++) {
    const s = skipInert(src, k)
    if (s >= 0) { k = s - 1; continue }
    if (src[k] === '{') d++
    else if (src[k] === '}') { d--; if (d === 0) return { text: src.slice(i, k + 1), fast: false } }
  }
  return null
}

/**
 * 切出一个声明的整段。认这几种声明形式：
 *
 *   · `function NAME(...) {...}` / `const NAME = ...`（含箭头、computed、ref）
 *   · `type NAME = ...` / `interface NAME {...}`
 *
 * 切不出来返回 `null`。**切出来但结构不闭合 ⇒ 抛错**（见文件头「结构性硬闸」）——
 * 那种切片比 `null` 更危险：它会安安静静地拿去比对，报一个没有意义的「逐字一致」。
 */
export function sliceFn(src, name) {
  const r = rawSlice(src, name)
  if (r == null) return null
  if (r.text != null && !r.fast) {
    const b = bracketBalance(r.text)
    if (b.depth !== 0 || b.min < 0 || b.open) {
      throw new Error(
        `切片不平衡 —— 清单或判据有问题：${name}\n` +
          `  切出来的这段：括号收支 ${b.depth}、过程最深 ${b.min}、末尾未闭合的串/块注释 ${b.open}\n` +
          `  ⇒ 没切到声明的结尾。**这一段不许拿去比对**（比了也是假的）。\n` +
          `  先看 lib/extract-movecheck-core.mjs 文件头的「能力边界」与「终点判据」：\n` +
          `  多半是这个形状还没被 sliceFn 覆盖；别把它登记进清单，也别改清单去迁就它。`,
      )
    }
  }
  return r.text
}

/**
 * 应用声明的改写；`from` 找不到就报错（规则失效比差异漏网更危险）。
 *
 * ⚠️ 语义是**逐条朴素 `split/join`**（不是正则）。所以规则一律要**带边界**：
 *    写 `dialog.warning({` 而不是 `dialog` —— 裸名会把别的标识符一起改坏
 *    （例：写 `load` 会顺手打到 `loadedIds` 上）。
 *
 * ⚠️ `rules` 的形状是 `{ 名字: [{from, to}, …] }`。**规则从哪来由调用侧决定**
 *    （Home 版按 block 传、Hui 版传它的模块级 `REWRITES`）—— 这正是两版原本唯一的分歧，
 *    也是这个参数存在的理由。
 *
 * ⚠️ 调用顺序：**先 `norm()` 再 `applyRewrites()`**。`norm()` 去了行首缩进，
 *    多行的 `from` 片段匹配不上 —— 所以 `from` 要写成**归一化后**的样子。
 */
export function applyRewrites(name, text, rules) {
  let out = text
  for (const r of rules[name] || []) {
    if (!out.includes(r.from)) {
      throw new Error(`声明的改写失效：${name} 里找不到 from 片段\n  ${r.from.slice(0, 120)}`)
    }
    out = out.split(r.from).join(r.to)
  }
  return out
}
